const tools = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(tools, "../..");
const marker = "__WORKGRAPH_UI_CAPABILITY__";
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const types = new Map(
  Object.entries({
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".txt": "text/plain; charset=utf-8",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".gif": "image/gif",
    ".webp": "image/webp",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
  }),
);
function relative(file, projectRoot = root) {
  return path.relative(projectRoot, file).split(path.sep).join("/");
}
function ocamlString(bytes) {
  let result = '"';
  for (const byte of bytes) {
    if (byte >= 32 && byte <= 126 && byte !== 34 && byte !== 92)
      result += String.fromCharCode(byte);
    else if (byte === 34) result += '\\"';
    else if (byte === 92) result += "\\\\";
    else result += "\\" + byte.toString(10).padStart(3, "0");
  }
  return result + '"';
}
export function createEmbeddedAssets({ projectRoot = root } = {}) {
  const frontend = path.join(projectRoot, "ui/frontend");
  const tools = path.join(projectRoot, "ui/tools");
  const dist = path.join(frontend, "dist");
  if (!existsSync(path.join(dist, "index.html")))
    throw new Error("UI assets missing: run ./dev-ui frontend after implementing src/main.tsx");
  const buildStamp = readBuildStamp(projectRoot);
  const notices = createNotices(frontend);
  const assets = filesUnder(dist)
    .filter((file) => !path.relative(dist, file).startsWith(".vite" + path.sep))
    .map((file) => ({
      path: "/" + path.relative(dist, file).split(path.sep).join("/"),
      body: readFileSync(file),
    }));
  assets.push({
    path: "/frontend-notices.txt",
    body: Buffer.from(notices.text),
  });
  assets.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  if (assets.length > 128 || new Set(assets.map((asset) => asset.path)).size !== assets.length)
    throw new Error("Asset count/duplicate path limit");
  let total = 0;
  for (const asset of assets) {
    if (
      !/^\/[A-Za-z0-9._/-]+$/.test(asset.path) ||
      asset.path.includes("..") ||
      asset.path.includes("//")
    )
      throw new Error(`Unsafe asset path ${asset.path}`);
    asset.content_type = types.get(path.extname(asset.path));
    if (!asset.content_type) throw new Error(`Unreviewed asset extension ${asset.path}`);
    if (asset.body.length > 8 * 1024 * 1024) throw new Error(`Asset exceeds8MiB: ${asset.path}`);
    total += asset.body.length;
    asset.sha256 = sha256(asset.body);
  }
  if (total > 16 * 1024 * 1024) throw new Error("Embedded asset total exceeds16MiB");
  const index = assets.find((asset) => asset.path === "/index.html").body.toString("utf8");
  if (Buffer.byteLength(index) > 65536 || index.split(marker).length !== 2)
    throw new Error("Bootstrap index must contain exactly one capability marker and fit64KiB");
  validateBootstrap(index, marker, new Set(assets.map((asset) => asset.path)));
  const lock = JSON.parse(readFileSync(path.join(frontend, "package-lock.json"), "utf8"));
  const manifest = {
    schema_version: 1,
    package_version: lock.version,
    input_sha256: buildStamp.input_sha256,
    lock_sha256: sha256(readFileSync(path.join(frontend, "package-lock.json"))),
    generator_runtime: { node: process.versions.node },
    required_toolchain: JSON.parse(readFileSync(path.join(tools, "toolchain.json"), "utf8")),
    runtime_dependencies: notices.inventory,
    assets: assets.map(({ path, content_type, sha256, body }) => ({
      path,
      content_type,
      sha256,
      size_bytes: String(body.length),
    })),
  };
  const manifestJson = JSON.stringify(manifest, null, 2) + "\n";
  const records = assets
    .map(
      (asset) =>
        `  { path = ${ocamlString(Buffer.from(asset.path))}\n  ; content_type = ${ocamlString(Buffer.from(asset.content_type))}\n  ; sha256 = ${ocamlString(Buffer.from(asset.sha256))}\n  ; body = ${ocamlString(asset.body)}\n  }`,
    )
    .join("\n; ");
  const ml = `(* Generated by ui/tools/embed-assets.mjs; do not edit. *)\n\n[@@@ocamlformat "disable"]\nopen! Core\n\ntype t = { path : string; content_type : string; sha256 : string; body : string }\n\nlet capability_marker = ${ocamlString(Buffer.from(marker))}\nlet manifest_json = ${ocamlString(Buffer.from(manifestJson))}\nlet manifest_sha256 = "${sha256(manifestJson)}"\nlet all = [\n${records}\n]\nlet find path = List.find all ~f:(fun asset -> String.equal asset.path path)\n`;
  return { manifestJson, ml, notices: notices.text, manifest };
}
export function checkOrWrite(check, options = {}) {
  const generated = createEmbeddedAssets(options);
  const output = path.join(options.projectRoot ?? root, "ui/tools/embedded");
  mkdirSync(output, { recursive: true });
  for (const [name, bytes] of [
    ["manifest.json", generated.manifestJson],
    ["generated/workgraph_ui_assets.ml", generated.ml],
    ["frontend-notices.txt", generated.notices],
  ]) {
    const file = path.join(output, name);
    if (check) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== bytes)
        throw new Error(`Stale embedded assets: ${relative(file)}; run ./dev-ui frontend`);
    } else {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, bytes);
    }
  }
  console.log(
    `${check ? "Checked" : "Embedded"} ${generated.manifest.assets.length} assets; manifest ${sha256(generated.manifestJson)}`,
  );
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some((arg) => arg !== "--check"))
    throw new Error("Usage: node ui/tools/embed-assets.mjs [--check]");
  checkOrWrite(process.argv.includes("--check"));
}
