#!/usr/bin/env python3
"""Generate/check portable discovery references from offline executable metadata.

python3 tools/generate_discovery_reference.py --binary /absolute/workgraph \
    --output skills/workgraph/references/discovery
Add --check to detect drift without writing. No daemon, context or network needed.
"""
import argparse
import json
import posixpath
import re
import subprocess
from pathlib import Path
from urllib.parse import unquote

from generate_api_reference import canonical, reconcile, sha, table_cell

GENERATOR = 'workgraph-discovery-reference'
ID = re.compile(r'[a-z][a-z0-9_]*(?:[.-][a-z][a-z0-9_]*)*\Z')


def inventory(catalog):
    if (not isinstance(catalog, dict) or set(catalog) != {'capabilities', 'groups', 'entries'} or
            not all(isinstance(catalog[key], list) and catalog[key] for key in catalog)):
        raise ValueError('expected nonempty executable discovery catalog')
    maps = []
    for key, field in [('capabilities', 'id'), ('groups', 'id'), ('entries', 'name')]:
        rows = {}
        for row in catalog[key]:
            if not isinstance(row, dict) or not isinstance(row.get(field), str) or not ID.fullmatch(row[field]):
                raise ValueError('invalid discovery identity in ' + key)
            if row[field] in rows:
                raise ValueError('duplicate discovery identity: ' + row[field])
            rows[row[field]] = row
        maps.append(rows)
    capabilities, groups, entries = maps
    for capability in capabilities.values():
        if not capability.get('groups') or any(name not in groups for name in capability['groups']):
            raise ValueError('capability must link known groups: ' + capability['id'])
    for group in groups.values():
        if any(name not in entries for name in group['start_with']):
            raise ValueError('unknown group starting point: ' + group['id'])
    for entry in entries.values():
        if entry.get('kind') not in {'method', 'helper', 'workflow'} or entry.get('capability') not in capabilities:
            raise ValueError('invalid entry kind/capability: ' + entry['name'])
        if any(name not in entries for name in entry.get('related', [])):
            raise ValueError('unknown related discovery entry: ' + entry['name'])
    return capabilities, groups, entries


def reference_link(reference, label='Focused reference'):
    if not isinstance(reference, str) or not reference or reference.startswith('/') or '\\' in reference:
        raise ValueError('expected a skill-relative reference path')
    return '[' + label + '](' + posixpath.relpath(reference, 'references/discovery') + ')'


def page(kind, identity):
    return kind + '.' + identity + '.md'


def entry_link(entry):
    if entry['kind'] == 'workflow':
        return '[' + entry['name'] + '](' + entry['name'] + '.md)'
    return reference_link(entry['reference'], entry['name'])


def entry_table(entries):
    text = '| Entry | Kind | When to use |\n| --- | --- | --- |\n'
    for entry in sorted(entries, key=lambda row: (row['kind'], row['name'])):
        text += '| ' + entry_link(entry) + ' | ' + entry['kind'] + ' | ' + table_cell(entry['use_when']) + ' |\n'
    return text + '\n'


def render(catalog):
    capabilities, groups, entries = inventory(catalog)
    files = {}
    notice = 'Generated from `workgraph discover --catalog`. Do not edit this file.\n\n'
    index = '# Discover Workgraph capabilities\n\n' + notice
    index += '''Use this compact index to choose an area, then load one capability, family or
workflow page. Discovery describes the CLI; it does not search recorded workspace
content or infer permission to act. All discovery commands work offline without a
context file, socket or daemon.

```sh
workgraph capabilities
workgraph discover 'ask another agent a blocking question'
workgraph discover 'save test output' --kind workflow --limit 3
workgraph help request
workgraph help workflow.ID
```

Use `capabilities ID` for one category and `discover 'intent text'` for ranked
methods, local helpers and workflow recipes. `--capability ID` and `--kind
method|helper|workflow` narrow discovery; `--limit` accepts 1..20 (default 5).
Both commands support `--output text|json`. `discover --catalog` returns the
complete metadata inventory without request/result schemas. Search is lexical:
try a shorter description or a capability when no result fits. A suggested recipe
still needs the method's preconditions, user scope and runtime checks.

Continue with `help FAMILY` for its decision card, `help workflow.ID` for a recipe,
`help METHOD` for inputs, examples and preconditions, `fields METHOD` for structured
input discovery, and `schema METHOD` for complete request/result validation.
`methods --core` is a concise everyday list; core/advanced are convenience tiers,
not permissions. The [API index](../api/index.md) remains exhaustive.

`search.query` searches recorded workspace content. `history.search` searches
imported conversation history under its capture. Neither discovers CLI features.
The capabilities here also differ from a registered run's declared eligibility
capabilities; discovery grants no authority and makes no claim about process life.

| Capability | Purpose |\n| --- | --- |\n'''
    for capability in capabilities.values():
        identity = capability['id']
        index += '| [' + capability['title'] + '](' + page('capability', identity) + ') | ' + table_cell(capability['summary']) + ' |\n'
        text = '# ' + capability['title'] + '\n\n' + notice + capability['summary'] + '\n\n'
        text += '`workgraph capabilities ' + identity + '` · ' + reference_link(capability['reference']) + '\n\n'
        text += '## Families\n\n| Family | Choose it when |\n| --- | --- |\n'
        for group_id in capability['groups']:
            group = groups[group_id]
            text += '| [' + group_id + '](' + page('group', group_id) + ') | ' + table_cell(group['use_when']) + ' |\n'
        special = [entry for entry in entries.values() if entry['capability'] == identity and entry['kind'] != 'method']
        if special:
            text += '\n## Helpers and workflows\n\n' + entry_table(special)
        text += '\n[Discovery index](index.md)\n'
        files[page('capability', identity)] = text.encode()
    for group in groups.values():
        identity = group['id']
        text = '# ' + identity + '\n\n' + notice + group['summary'] + '\n\n'
        text += '**Use when:** ' + group['use_when'] + '\n\n**Choose carefully:** ' + group['distinction'] + '\n\n'
        text += '**Start with:** ' + ', '.join(entry_link(entries[name]) for name in group['start_with']) + '.\n\n'
        text += '`workgraph help ' + identity + '` · ' + reference_link(group['reference']) + '\n\n'
        methods = [entry for entry in entries.values() if entry['kind'] == 'method' and (entry['name'] == identity or entry['name'].startswith(identity + '.'))]
        if methods:
            text += entry_table(methods)
        text += '[Discovery index](index.md)\n'
        files[page('group', identity)] = text.encode()
    workflows = [entry for entry in entries.values() if entry['kind'] == 'workflow']
    for entry in workflows:
        text = '# ' + entry['name'] + '\n\n' + notice + entry['summary'] + '\n\n'
        text += '**Use when:** ' + entry['use_when'] + '\n\n'
        text += '`workgraph help ' + entry['name'] + '` · ' + reference_link(entry['reference']) + '\n\n'
        text += '\n'.join(str(index) + '. ' + step for index, step in enumerate(entry['steps'], 1)) + '\n\n'
        if entry['related']:
            text += '**Related entries:** ' + ', '.join(entry_link(entries[name]) for name in entry['related']) + '.\n\n'
        text += 'Read exact method contracts before writes. Preserve saved retry identities, actual ownership tokens, revision guards and immutable evidence pins. The harness performs external work and controls processes.\n\n'
        text += '[Discovery index](index.md)\n'
        files[entry['name'] + '.md'] = text.encode()
    index += '\n## Workflows\n\n' + entry_table(workflows)
    index += 'Regenerate with `python3 tools/generate_discovery_reference.py --binary /absolute/workgraph --output skills/workgraph/references/discovery`; add `--check` for drift detection.\n'
    files['index.md'] = index.encode()
    manifest = {'generator': GENERATOR, 'catalog_sha256': sha(canonical(catalog).encode()),
                'capability_count': len(capabilities), 'group_count': len(groups), 'workflow_count': len(workflows),
                'files': {name: sha(data) for name, data in sorted(files.items())}}
    files['MANIFEST.json'] = (json.dumps(manifest, sort_keys=True, indent=2) + '\n').encode()
    return files


def validate_links(directory, files):
    """Check generated links against this inventory or the installed skill tree."""
    directory = Path(directory).absolute()
    skill = directory.parent.parent
    for name, data in files.items():
        if not name.endswith('.md'):
            continue
        for target in re.findall(r'\]\(([^\s)]+)\)', data.decode()):
            path = unquote(target.split('#', 1)[0])
            resolved = (directory / path).resolve()
            if not resolved.is_relative_to(skill.resolve()):
                raise ValueError('generated discovery link escapes skill: ' + target)
            if resolved.parent == directory.resolve() and resolved.name in files:
                continue
            if not resolved.is_file():
                raise ValueError('generated discovery link is missing: ' + target)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    binary = args.binary.resolve(strict=True)
    catalog = json.loads(subprocess.check_output([str(binary), 'discover', '--catalog'], timeout=30))
    files = render(catalog)
    validate_links(args.output, files)
    reconcile(args.output, files, check=args.check, generator=GENERATOR)
    print(canonical({'status': 'checked' if args.check else 'generated', 'files': len(files)}))


if __name__ == '__main__':
    main()
