#!/usr/bin/env python3
"""Generate/check the portable skill README from the repository's maintained README.

The source README owns its prose, Mermaid diagrams and exact inline script bytes.
Only Markdown links outside fenced code blocks are relocated for the copied skill.
Repository-only material stays a link to GitHub rather than becoming bundled copies.
"""
import argparse
from pathlib import Path
import re
import sys
from urllib.parse import quote, urlsplit

REPOSITORY = 'https://github.com/dakotamurphyucf/workgraph'
SKILL_PREFIX = 'skills/workgraph/'
LINK = re.compile(r'(\]\()([^\s)]+)(\))')
FENCE = re.compile(r'^\s*(`{3,}|~{3,})')
NOTICE = '''<!-- Generated by tools/sync_skill_readme.py from the repository README.md; do not edit this copy. -->

'''
PORTABLE_CONTEXT = '''This is the complete team and orchestrator overview bundled with the Workgraph
skill. Read the workflows and participant prompts relevant to your assignment;
use [SKILL.md](SKILL.md) and the local references for operation-specific contracts.

The examples and inline scripts below retain their repository spelling. A path
beginning `skills/workgraph/` means this skill folder: when using a copied bundle,
replace that prefix with your absolute skill-directory path. `./dev` and source
build commands require a Workgraph repository checkout; ordinary CLI usage does
not. Source-only documentation links open the repository online. The maintained
inline script bodies are unchanged; runnable copies are in [scripts](scripts/).

'''


def relocate(target, root):
    """Keep bundled targets local and point source-only targets to the repository."""
    if target.startswith('#') or urlsplit(target).scheme or target.startswith('//'):
        return target
    path, separator, fragment = target.partition('#')
    suffix = separator + fragment
    if path.startswith(SKILL_PREFIX):
        return path[len(SKILL_PREFIX):] + suffix
    if path == 'docs/migration.md':
        return 'references/migration.md' + suffix
    if path == 'LICENSE':
        return 'LICENSE.txt' + suffix
    if path == 'README.md':
        return 'README.md' + suffix
    kind = 'tree' if (root / path).is_dir() else 'blob'
    return f'{REPOSITORY}/{kind}/main/{quote(path, safe="/")}{suffix}'


def render(root):
    text = (root / 'README.md').read_text()
    output = []
    fence_character = None
    fence_length = 0
    for line in text.splitlines(keepends=True):
        match = FENCE.match(line)
        if match:
            marker = match.group(1)
            if fence_character is None:
                fence_character, fence_length = marker[0], len(marker)
            elif marker[0] == fence_character and len(marker) >= fence_length:
                fence_character = None
            output.append(line)
        elif fence_character is not None:
            output.append(line)
        else:
            output.append(LINK.sub(lambda m: m[1] + relocate(m[2], root) + m[3], line))
    text = ''.join(output)
    heading = '# Workgraph\n\n'
    if not text.startswith(heading):
        raise ValueError('Expected the maintained README to start with # Workgraph')
    return NOTICE + heading + PORTABLE_CONTEXT + text[len(heading):]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='reject a stale or missing generated copy')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1],
                        help='repository root (default: parent of this tools directory)')
    args = parser.parse_args()
    root = args.root.resolve()
    destination = root / 'skills/workgraph/README.md'
    expected = render(root)
    if args.check:
        if not destination.is_file() or destination.read_text() != expected:
            print('Skill README is stale; run python3 tools/sync_skill_readme.py.', file=sys.stderr)
            return 1
        print('Skill README is synchronized.')
    else:
        destination.write_text(expected)
        print('Updated skills/workgraph/README.md.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
